//! `report`: one scan of the root, then catalog rules, projects and large files
//! measured from the same tree (PLAN.md §3, §4).

use crate::catalog::{self, Rule, Safety, Tools};
use crate::explain::Explanation;
use crate::projects::{self, Project};
use crate::{scan, DirNode, ScanOptions, ScanResult};
use serde::Serialize;
use std::collections::HashMap;
use std::io;
use std::path::{Path, PathBuf};

#[derive(Debug, Serialize)]
pub struct Report {
    pub root: PathBuf,
    pub home: PathBuf,
    pub generated_at: i64,
    pub scan: ScanSummary,
    pub volume: Option<Volume>,
    pub rules: Vec<RuleReport>,
    pub projects: Vec<Project>,
    pub large_files: Vec<LargeFileReport>,
    /// Locations that couldn't be read (EPERM): need Full Disk Access.
    pub needs_full_disk_access: Vec<PathBuf>,
    /// Biggest folders directly under the root (the "where did it go" view).
    pub top_dirs: Vec<PathSize>,
    /// Bytes in files directly inside the root.
    pub root_files_bytes: u64,
    /// The scan tree, kept for the folder browser (not serialized: ~600k nodes).
    #[serde(skip)]
    pub tree: Option<DirNode>,
}

/// One folder's contents for the folder browser.
#[derive(Debug, Serialize)]
pub struct FolderListing {
    pub path: PathBuf,
    pub size: u64,
    pub files: u64,
    pub info: Explanation,
    /// Bytes of files directly in this folder (not in subfolders).
    pub files_bytes: u64,
    pub direct_files: u64,
    pub items: Vec<FolderItem>,
    /// Subfolders left out of `items` (beyond the limit).
    pub more_items: usize,
    pub more_bytes: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct FolderItem {
    pub name: String,
    pub path: PathBuf,
    pub size: u64,
    pub files: u64,
    pub newest_mtime: i64,
    pub has_children: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
    pub info: Explanation,
}

impl Report {
    /// What `path` is and whether it's safe to delete. Catalog rules and project
    /// build folders override the general macOS conventions.
    pub fn explain(&self, path: &Path) -> Explanation {
        for r in &self.rules {
            if r.rule.generic {
                continue;
            }
            for p in &r.paths {
                if path == p.path || path.starts_with(&p.path) {
                    let inside = path != p.path;
                    let text = if r.leftover {
                        r.rule.leftover_explanation.clone().unwrap_or_else(|| r.rule.explanation.clone())
                    } else {
                        r.rule.explanation.clone()
                    };
                    return Explanation {
                        label: if inside { format!("Part of {}", r.name) } else { r.name.clone() },
                        safety: Some(r.safety),
                        explanation: format!("{text} Comes back: {}", if r.leftover { "no, the app is uninstalled." } else { r.rule.comes_back.as_str() }),
                        rule_id: Some(r.id.clone()),
                        owner_hint: None,
                    };
                }
            }
        }
        for p in &self.projects {
            for a in &p.artifacts {
                if path == a.path || path.starts_with(&a.path) {
                    let ignored = a.git_ignored != Some(false);
                    return Explanation {
                        label: format!("Build folder ({})", a.name),
                        safety: Some(if ignored { a.safety } else { Safety::Review }),
                        explanation: if ignored {
                            format!("Generated by the project's tools; rebuilt by {}. Safe to delete when you're not working on the project.", a.regenerate)
                        } else {
                            "Looks like a build folder, but git doesn't ignore it: it may contain committed files. Check before deleting.".into()
                        },
                        rule_id: None,
                        owner_hint: None,
                    };
                }
            }
            if path == p.path {
                return Explanation {
                    label: format!("Project ({})", p.kinds.join(", ")),
                    safety: Some(Safety::Review),
                    explanation: format!(
                        "Source code: yours. Only its build folders ({}) are safe to delete; they're rebuilt by the project's tools.",
                        p.artifacts.iter().map(|a| a.name.as_str()).collect::<Vec<_>>().join(", ")
                    ),
                    rule_id: None,
                    owner_hint: None,
                };
            }
        }
        crate::explain::explain(path, &self.home)
    }

    /// Size of a folder from the scan tree (None if not in it).
    pub fn size_of(&self, path: &Path) -> Option<&DirNode> {
        let rel = path.strip_prefix(&self.root).ok()?;
        self.tree.as_ref()?.find(rel)
    }

    /// Contents of `path` (must be inside the scanned root), biggest first.
    pub fn listing(&self, path: &Path, limit: usize) -> Option<FolderListing> {
        let tree = self.tree.as_ref()?;
        let rel = path.strip_prefix(&self.root).ok()?;
        let node = tree.find(rel)?;
        let mut kids: Vec<&DirNode> = node.children.iter().collect();
        kids.sort_by_key(|c| std::cmp::Reverse(c.size));
        let shown = kids.len().min(limit);
        let items = kids[..shown]
            .iter()
            .map(|c| {
                let p = path.join(&c.name);
                FolderItem {
                    name: c.name.clone(),
                    info: self.explain(&p),
                    path: p,
                    size: c.size,
                    files: c.files,
                    newest_mtime: c.newest_mtime,
                    has_children: !c.children.is_empty(),
                    error: c.error.clone(),
                }
            })
            .collect();
        let child_files: u64 = node.children.iter().map(|c| c.files).sum();
        Some(FolderListing {
            path: path.to_path_buf(),
            size: node.size,
            files: node.files,
            info: self.explain(path),
            files_bytes: node.size - node.children.iter().map(|c| c.size).sum::<u64>(),
            direct_files: node.files - child_files,
            items,
            more_items: kids.len() - shown,
            more_bytes: kids[shown..].iter().map(|c| c.size).sum(),
            error: node.error.clone(),
        })
    }
}

#[derive(Debug, Serialize)]
pub struct ScanSummary {
    pub total_bytes: u64,
    pub files: u64,
    pub dirs: u64,
    pub unreadable_dirs: u64,
    pub hardlink_bytes_deduped: u64,
    pub elapsed_ms: u128,
}

#[derive(Debug, Serialize)]
pub struct Volume {
    /// APFS container size (shared by all volumes on the disk).
    pub total_bytes: u64,
    pub free_bytes: u64,
    /// Used by all volumes in the container.
    pub used_bytes: u64,
    /// Used by the scanned volume alone (the Data volume: what `df` shows).
    pub volume_used_bytes: Option<u64>,
}

#[derive(Debug, Serialize)]
pub struct PathSize {
    pub path: PathBuf,
    pub size: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct RuleReport {
    pub id: String,
    pub name: String,
    pub category: String,
    pub safety: Safety,
    /// Bytes attributed to this rule (generic rules exclude nested rules).
    pub size: u64,
    pub found: bool,
    pub paths: Vec<PathSize>,
    pub path_source: &'static str,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub details: Vec<PathSize>,
    /// Biggest children, for itemized (generic) rules.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub items: Vec<PathSize>,
    pub tool: Option<PathBuf>,
    pub tool_missing: bool,
    pub leftover: bool,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub running_apps: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
    pub rule: Rule,
}

#[derive(Debug, Serialize)]
pub struct LargeFileReport {
    pub path: PathBuf,
    pub size: u64,
    pub mtime: i64,
    pub kind: &'static str,
}

pub struct ReportOptions {
    pub scan: ScanOptions,
    pub git: bool,
    pub catalog_dir: Option<PathBuf>,
    /// Home folder for `~` in rules and for path validation (default: $HOME).
    /// Tests point it at a fixture tree.
    pub home: Option<PathBuf>,
    /// Live scan counters (for a progress display).
    pub progress: Option<std::sync::Arc<crate::Progress>>,
}

impl Default for ReportOptions {
    fn default() -> Self {
        ReportOptions {
            scan: ScanOptions::default(),
            git: true,
            catalog_dir: None,
            home: None,
            progress: None,
        }
    }
}

pub fn home_dir() -> PathBuf {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| "/".into())
}

pub fn build(root: &Path, opts: &ReportOptions) -> io::Result<Report> {
    let home = opts.home.clone().unwrap_or_else(home_dir);
    let rules = match &opts.catalog_dir {
        Some(d) => catalog::load_dir(d)?,
        None => catalog::load_embedded(),
    };
    let tools = Tools::new(&home);
    // Resolving paths can run tool commands (npm config get cache...): do it
    // while the scan runs.
    let (resolved, result) = std::thread::scope(|s| {
        let h = s.spawn(|| {
            use rayon::prelude::*;
            rules
                .par_iter()
                .map(|r| r.resolve(&home, &tools))
                .collect::<Vec<_>>()
        });
        let result = match &opts.progress {
            Some(p) => crate::scan_with_progress(root, &opts.scan, p),
            None => scan(root, &opts.scan),
        };
        (h.join().unwrap(), result)
    });
    let result = result?;
    let root = result.root.clone();
    let set_phase = |p: u64| {
        if let Some(pr) = &opts.progress {
            pr.phase.store(p, std::sync::atomic::Ordering::Relaxed);
        }
    };
    set_phase(crate::PHASE_MEASURING);
    let processes = catalog::running_process_names();

    let mut size_of = Sizer {
        result: &result,
        root: &root,
        extra: HashMap::new(),
        opts: &opts.scan,
    };
    // All non-generic rule paths, so generic rules can subtract them.
    let claimed: Vec<PathBuf> = rules
        .iter()
        .zip(&resolved)
        .filter(|(r, _)| !r.generic)
        .flat_map(|(_, res)| res.paths.clone())
        .collect();

    for c in &claimed {
        size_of.path(c);
    }

    let mut reports = Vec::new();
    for (rule, res) in rules.iter().zip(resolved) {
        let mut paths = Vec::new();
        for p in &res.paths {
            paths.push(size_of.path(p));
        }
        let mut size: u64 = paths.iter().map(|p| p.size).sum();
        let mut items = Vec::new();
        if rule.generic {
            for p in &res.paths {
                let inner: Vec<&PathBuf> = claimed
                    .iter()
                    .filter(|c| c.starts_with(p) && *c != p)
                    .collect();
                for c in &inner {
                    size = size.saturating_sub(size_of.path(c).size);
                }
                if rule.itemize {
                    if let Some(node) = size_of.node(p) {
                        let mut kids: Vec<PathSize> = node
                            .children
                            .iter()
                            .map(|c| (p.join(&c.name), c))
                            .filter(|(cp, _)| !inner.contains(&cp))
                            .map(|(cp, c)| {
                                // Subtract claimed paths nested inside this child.
                                let nested: u64 = inner
                                    .iter()
                                    .filter(|i| i.starts_with(&cp))
                                    .map(|i| size_of.cached(i))
                                    .sum();
                                PathSize {
                                    path: cp,
                                    size: c.size.saturating_sub(nested),
                                    error: c.error.clone(),
                                }
                            })
                            .filter(|ps| ps.size > 0)
                            .collect();
                        kids.sort_by_key(|x| std::cmp::Reverse(x.size));
                        kids.truncate(15);
                        items.extend(kids);
                    }
                }
            }
        }
        let details = res
            .paths
            .first()
            .map(|base| {
                rule.details
                    .iter()
                    .map(|d| size_of.path(&base.join(d)))
                    .filter(|d| d.error.is_none())
                    .collect()
            })
            .unwrap_or_default();
        let tool = rule.tool_path(&tools);
        let leftover = rule.is_leftover() && !res.paths.is_empty();
        let running_apps: Vec<String> = rule
            .quit_apps
            .iter()
            .filter(|a| processes.iter().any(|p| p == *a))
            .cloned()
            .collect();
        let mut note = None;
        if rule.special.as_deref() == Some("tm-snapshots") {
            let n = tm_snapshot_count();
            note = Some(match n {
                Some(0) => "no local snapshots".into(),
                Some(n) => format!("{n} local snapshot(s); size can't be measured per snapshot"),
                None => "tmutil unavailable".into(),
            });
        }
        if paths.iter().any(|p| {
            p.error
                .as_deref()
                .is_some_and(|e| e.contains("not permitted"))
        }) {
            note = Some("needs Full Disk Access to measure".into());
        }
        reports.push(RuleReport {
            id: rule.id.clone(),
            name: rule.name.clone(),
            category: rule.category.clone(),
            safety: rule.safety,
            found: !res.paths.is_empty() || rule.special.is_some(),
            size,
            paths,
            path_source: res.source,
            details,
            items,
            tool_missing: rule.tool.is_some() && tool.is_none(),
            tool,
            leftover,
            running_apps,
            note,
            rule: rule.clone(),
        });
    }
    reports.sort_by_key(|x| std::cmp::Reverse(x.size));

    let mut excluded: Vec<PathBuf> = claimed.clone();
    excluded.extend(
        reports
            .iter()
            .filter(|r| r.rule.generic)
            .flat_map(|r| r.paths.iter().map(|p| p.path.clone())),
    );
    let mut projects = projects::detect(&result.tree, &root, &excluded);
    if opts.git {
        set_phase(crate::PHASE_GIT);
        let git = tools.find("git", &[]);
        projects::fill_git(&mut projects, git.as_deref());
    }
    projects.sort_by_key(|x| std::cmp::Reverse(x.artifact_bytes));

    let mut large_files = Vec::new();
    let mut large_excluded = excluded.clone();
    large_excluded.extend(
        projects
            .iter()
            .flat_map(|p| p.artifacts.iter().map(|a| a.path.clone())),
    );
    collect_large(
        &result.tree,
        &root,
        &large_excluded,
        &home,
        &mut large_files,
    );
    large_files.sort_by_key(|x| std::cmp::Reverse(x.size));

    let mut needs_fda = Vec::new();
    collect_eperm(&result.tree, &root, &mut needs_fda);

    Ok(Report {
        home,
        generated_at: now(),
        scan: ScanSummary {
            total_bytes: result.total_bytes,
            files: result.stats.files,
            dirs: result.stats.dirs,
            unreadable_dirs: result.stats.dir_errors,
            hardlink_bytes_deduped: result.stats.hardlink_bytes_deduped,
            elapsed_ms: result.elapsed_ms,
        },
        volume: volume(&root),
        rules: reports,
        projects,
        large_files,
        needs_full_disk_access: needs_fda,
        top_dirs: {
            let mut v: Vec<PathSize> = result
                .tree
                .children
                .iter()
                .map(|c| PathSize { path: root.join(&c.name), size: c.size, error: c.error.clone() })
                .collect();
            v.sort_by_key(|x| std::cmp::Reverse(x.size));
            v
        },
        root_files_bytes: result.tree.size - result.tree.children.iter().map(|c| c.size).sum::<u64>(),
        root,
        tree: Some(result.tree),
    })
}

/// Sizes paths from the scan tree when they're inside the root, by a separate
/// scan otherwise. Memoized.
struct Sizer<'a> {
    result: &'a ScanResult,
    root: &'a Path,
    extra: HashMap<PathBuf, (u64, Option<String>)>,
    opts: &'a ScanOptions,
}

impl Sizer<'_> {
    fn node(&self, p: &Path) -> Option<&DirNode> {
        let rel = p.strip_prefix(self.root).ok()?;
        self.result.tree.find(rel)
    }

    /// Size of a path already measured by `path` (0 if not).
    fn cached(&self, p: &Path) -> u64 {
        self.node(p)
            .map(|n| n.size)
            .or_else(|| self.extra.get(p).map(|e| e.0))
            .unwrap_or(0)
    }

    fn path(&mut self, p: &Path) -> PathSize {
        if let Some(n) = self.node(p) {
            return PathSize {
                path: p.to_path_buf(),
                size: n.size,
                error: n.error.clone(),
            };
        }
        let (size, error) = self.extra.entry(p.to_path_buf()).or_insert_with(|| {
            match std::fs::symlink_metadata(p) {
                Err(e) => (0, Some(e.to_string())),
                Ok(m) if !m.is_dir() => {
                    use std::os::unix::fs::MetadataExt;
                    (m.blocks() * 512, None)
                }
                Ok(_) => match scan(
                    p,
                    &ScanOptions {
                        large_file_threshold: 0,
                        ..self.opts.clone()
                    },
                ) {
                    Ok(r) => (r.total_bytes, r.tree.error.clone()),
                    Err(e) => (0, Some(e.to_string())),
                },
            }
        });
        PathSize {
            path: p.to_path_buf(),
            size: *size,
            error: error.clone(),
        }
    }
}

fn collect_large(
    n: &DirNode,
    path: &Path,
    excluded: &[PathBuf],
    home: &Path,
    out: &mut Vec<LargeFileReport>,
) {
    if excluded.iter().any(|e| path.starts_with(e)) || path.starts_with(home.join("Library")) {
        return;
    }
    for f in &n.large_files {
        out.push(LargeFileReport {
            path: path.join(&f.name),
            size: f.size,
            mtime: f.mtime,
            kind: file_kind(&f.name),
        });
    }
    for c in &n.children {
        if c.name == "node_modules" {
            continue;
        }
        collect_large(c, &path.join(&c.name), excluded, home, out);
    }
}

pub fn file_kind(name: &str) -> &'static str {
    let ext = name.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
    match ext.as_str() {
        "dmg" | "pkg" | "iso" | "xip" | "mpkg" | "exe" | "msi" => "installer",
        "pack" => "git pack",
        "zip" | "tar" | "gz" | "tgz" | "7z" | "rar" | "bz2" | "xz" | "zst" => "archive",
        "mp4" | "mov" | "mkv" | "avi" | "m4v" | "webm" => "video",
        "raw" | "qcow2" | "vmdk" | "vdi" | "img" | "utm" | "vhd" | "vhdx" => "disk image",
        "gguf" | "safetensors" | "bin" | "pt" | "ckpt" | "onnx" => "model / binary",
        "sqlite" | "db" => "database",
        _ => "other",
    }
}

fn collect_eperm(n: &DirNode, path: &Path, out: &mut Vec<PathBuf>) {
    if n.error
        .as_deref()
        .is_some_and(|e| e.contains("not permitted"))
    {
        out.push(path.to_path_buf());
    }
    for c in &n.children {
        collect_eperm(c, &path.join(&c.name), out);
    }
}

fn tm_snapshot_count() -> Option<usize> {
    let out = std::process::Command::new("/usr/bin/tmutil")
        .args(["listlocalsnapshots", "/"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(
        String::from_utf8_lossy(&out.stdout)
            .lines()
            .filter(|l| l.contains("com.apple.TimeMachine"))
            .count(),
    )
}

fn volume(p: &Path) -> Option<Volume> {
    use std::os::unix::ffi::OsStrExt;
    let c = std::ffi::CString::new(p.as_os_str().as_bytes()).ok()?;
    let mut st: libc::statfs = unsafe { std::mem::zeroed() };
    if unsafe { libc::statfs(c.as_ptr(), &mut st) } != 0 {
        return None;
    }
    let bs = st.f_bsize as u64;
    let total = st.f_blocks * bs;
    let free = st.f_bavail * bs;
    // APFS volumes share their container's space; "used" is what isn't free.
    Some(Volume {
        total_bytes: total,
        free_bytes: free,
        used_bytes: total - free,
        volume_used_bytes: volume_space_used(&c),
    })
}

/// ATTR_VOL_SPACEUSED: bytes used by this volume alone (what `df` reports).
fn volume_space_used(path: &std::ffi::CStr) -> Option<u64> {
    let mut al: libc::attrlist = unsafe { std::mem::zeroed() };
    al.bitmapcount = libc::ATTR_BIT_MAP_COUNT;
    al.volattr = libc::ATTR_VOL_INFO | libc::ATTR_VOL_SPACEUSED;
    #[repr(C, packed(4))]
    struct Buf {
        len: u32,
        used: libc::off_t,
    }
    let mut buf = Buf { len: 0, used: 0 };
    let rc = unsafe {
        libc::getattrlist(
            path.as_ptr(),
            &mut al as *mut _ as *mut libc::c_void,
            &mut buf as *mut _ as *mut libc::c_void,
            std::mem::size_of::<Buf>(),
            0,
        )
    };
    let used = buf.used;
    (rc == 0 && used > 0).then_some(used as u64)
}

fn now() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}
